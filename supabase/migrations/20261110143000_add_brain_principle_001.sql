<p>Instead, it investigates.</p>
<p>What opportunities has the individual pursued? What skills have they developed? What activities do they perform consistently? How do they respond to rejection? What barriers exist outside their control?</p>
<p>The objective is to identify whether there are actions the person can change to improve their situation.</p>
<p>The solution should emerge from understanding the person's actual circumstances, not from making assumptions about their character.</p>
